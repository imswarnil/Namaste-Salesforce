/* ════════════════════════════════════════════════════════════════════════════
   build-icon-bridge.mjs — restate NSDS's element-based icon rules for .ns-icon
   ----------------------------------------------------------------------------
   NSDS was written against an icon FONT and styles some icons by ELEMENT:

       .ns-buybox__list i { color: var(--color-brand-500); font-size: 1rem }

   This theme draws inline SVG (see partials/icons/README.md), so every one of
   those 59 selectors misses. The icon still renders — at the wrong size, in
   the wrong colour, on the wrong baseline — which is a much quieter failure
   than one that renders nothing.

   So: parse the vendored bundle, find every rule whose selector matches the
   bare `i` element, and re-emit it with `i` replaced by `.ns-icon`. Nothing is
   invented; the declarations are upstream's own.

       node scripts/build-icon-bridge.mjs           regenerate
       node scripts/build-icon-bridge.mjs --check   fail if stale (CI)

   ⚠ Generated. Do not edit assets/css/theme/9-generated/icon-bridge.css — a re-run
   silently reverts you. Fix it upstream in NS-Design-System instead, which
   is the actual repair: `i` → `:is(i, .ns-icon)` there deletes this file.
   ═══════════════════════════════════════════════════════════════════════ */

import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const SRC = 'assets/css/nsds/nsds.css';
const OUT = 'assets/css/theme/9-generated/icon-bridge.css';

/* The bare element, not a class or an attribute: ` i`, `>i`, `,i` — never
   `.ns-icon`, never `[data-i]`. A word boundary alone would match both. */
const ELEMENT_I = /(^|[\s>+~(,])i(?=$|[\s>+~:,.[)])/g;

const root = postcss.parse(readFileSync(SRC, 'utf8'), { from: SRC });
const out = postcss.root();
let count = 0;

root.walkRules(rule => {
    /* ELEMENT_I is /g and therefore stateful — reset before every test. */
    const matched = rule.selectors.filter(s => { ELEMENT_I.lastIndex = 0; return ELEMENT_I.test(s); });
    if (!matched.length) return;

    const bridged = matched.map(s => s.replace(ELEMENT_I, (m, lead) => `${lead}.ns-icon`));
    const clone = rule.clone({ selectors: bridged });
    clone.cleanRaws();

    /* Carry the at-rule context — a rule inside @media means something
       different outside it — but NOT @layer. Upstream's rules live in
       @layer ns-components; re-emitting that here would nest a sub-layer
       inside `components` rather than putting the bridge in `components`,
       which is the whole point of the file. */
    let node = clone, parent = rule.parent;
    while (parent && parent.type === 'atrule') {
        if (parent.name !== 'layer') {
            node = postcss.atRule({ name: parent.name, params: parent.params }).append(node);
        }
        parent = parent.parent;
    }
    out.append(node);
    count++;
});

const header = `/* ════════════════════════════════════════════════════════════════════════════
   icon-bridge.css — GENERATED by scripts/build-icon-bridge.mjs. Do not edit.
   ----------------------------------------------------------------------------
   NSDS styles ${count} icon rules by element (\`… i\`) because it was written
   against an icon font. This theme draws inline SVG, so those rules miss.
   Each rule below is upstream's own declaration block, re-selected for
   .ns-icon. Regenerate after ./scripts/sync-nsds.sh.

   The real fix is \`i\` → \`:is(i, .ns-icon)\` upstream, which deletes this file.
   ═══════════════════════════════════════════════════════════════════════ */

@layer components {
`;

const body = out.toString().split('\n').map(l => (l ? '  ' + l : l)).join('\n');
const css = `${header}${body}\n}\n`;

if (process.argv.includes('--check')) {
    const have = readFileSync(OUT, 'utf8');
    if (have !== css) {
        console.error(`✗ ${OUT} is stale — run \`node scripts/build-icon-bridge.mjs\` and commit.`);
        process.exit(1);
    }
    console.log(`✓ icon bridge current — ${count} rules`);
} else {
    writeFileSync(OUT, css);
    console.log(`✓ ${OUT} — ${count} rules bridged from ${SRC}`);
}
